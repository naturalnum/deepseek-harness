/** Map the current Root generator's JSON fields to exact byte ranges, without rewriting its document. */
import { isIP } from 'node:net'
import { CandidateError } from './inspect.mjs'

const fail = () => { throw new CandidateError('恢复配置字段未唯一确认；原配置未改写。') }

// JSON.parse validates the grammar; this walk retains byte positions and rejects duplicate member names.
function positions(bytes) {
  if (!Buffer.isBuffer(bytes) || !bytes.length) fail()
  const text = bytes.toString('utf8')
  if (!Buffer.from(text).equals(bytes)) fail()
  try { JSON.parse(text.replace(/^\uFEFF/, '')) } catch (_error) { fail() }
  const spans = new Map()
  let cursor = bytes.subarray(0, 3).equals(Buffer.from([239, 187, 191])) ? 3 : 0
  const space = () => { while ([9, 10, 13, 32].includes(bytes[cursor])) cursor++ }
  const string = () => {
    const start = cursor++
    while (bytes[cursor] !== 34) { if (bytes[cursor] === 92) cursor++; cursor++ }
    cursor++
    return JSON.parse(bytes.subarray(start, cursor).toString('utf8'))
  }
  const walk = path => {
    space()
    const start = cursor, marker = bytes[cursor]
    if (marker === 123 || marker === 91) {
      cursor++; space()
      const end = marker === 123 ? 125 : 93, keys = new Set()
      let index = 0
      while (bytes[cursor] !== end) {
        let key = index++
        if (marker === 123) {
          key = string()
          if (keys.has(key)) fail()
          keys.add(key); space(); cursor++; space()
        }
        walk([...path, key]); space()
        if (bytes[cursor] === 44) { cursor++; space() }
      }
      cursor++
    } else {
      if (marker === 34) string()
      else while (cursor < bytes.length && ![9, 10, 13, 32, 44, 93, 125].includes(bytes[cursor])) cursor++
    }
    spans.set(JSON.stringify(path), { start, end: cursor, value: JSON.parse(bytes.subarray(start, cursor).toString('utf8')) })
  }
  walk([])
  return spans
}

function canonicalUrl(value, originOnly) {
  if (typeof value !== 'string') fail()
  let url
  try { url = new URL(value) } catch (_error) { fail() }
  if (!['http:', 'https:'].includes(url.protocol) || url.username || url.password || url.search || url.hash
    || (originOnly ? url.origin !== value : url.href !== value)) fail()
  return value
}

/**
 * Locate the current generator's unique Root entries and all twelve hash/address/port tokens.
 * @param {object} input - Original rootBytes/deploymentBytes Buffers and fresh addresses: listenHost,
 * listenPort, internalAddress, databaseHost, databasePort, publicOrigin and lifecycleBaseUrl. This
 * accepts the JSON insert profile generated by generate-feature-root-profile-v3.mjs, never YAML
 * heuristics or global replacement. All untouched bytes, including BOM/CRLF, remain caller-owned.
 * @returns {object[]} Exact patches accepted by rebuildRecoveryFiles. No I/O or credentials parsing occurs.
 */
export function mapRecoveryConfiguration({ rootBytes, deploymentBytes, addresses }) {
  try {
    const root = positions(rootBytes), deployment = positions(deploymentBytes)
    const document = root.get('[]').value
    if (!Array.isArray(document) || document.length !== 1 || !Array.isArray(document[0]?.insert)) fail()
    const entry = id => {
      const indexes = document[0].insert.flatMap((row, index) => row?.id === id ? [index] : [])
      if (indexes.length !== 1) fail()
      return [0, 'insert', indexes[0], 'config']
    }
    if (!addresses || Object.keys(addresses).sort().join(',') !== 'databaseHost,databasePort,internalAddress,lifecycleBaseUrl,listenHost,listenPort,publicOrigin'
      || !isIP(addresses.listenHost) || !isIP(addresses.databaseHost)) fail()
    for (const key of ['listenPort', 'databasePort']) {
      if (!Number.isSafeInteger(addresses[key]) || addresses[key] < 1 || addresses[key] > 65535) fail()
    }
    canonicalUrl(addresses.internalAddress, true); canonicalUrl(addresses.publicOrigin, true)
    canonicalUrl(addresses.lifecycleBaseUrl, false)
    const patch = (source, spans, slot, path, value) => {
      const span = spans.get(JSON.stringify(path))
      if (!span || !['string', 'number'].includes(typeof span.value)) fail()
      const offset = span.start + (typeof span.value === 'string' ? 1 : 0)
      const expected = Buffer.from(String(span.value))
      // Escaped strings cannot be substituted as unquoted ASCII tokens.
      if (!source.subarray(offset, offset + expected.length).equals(expected)
        || offset + expected.length !== span.end - (typeof span.value === 'string' ? 1 : 0)) fail()
      return { slot, offset, expected, ...(value === undefined ? {} : { value: String(value) }) }
    }
    const r = (slot, id, path, value) => patch(rootBytes, root, 'root.' + slot, [...entry(id), ...path], value)
    const d = (slot, path, value) => patch(deploymentBytes, deployment, 'deployment.' + slot, path, value)
    return [
      r('storagePlanHash', 'files-root', ['staticStorage', 'planSha256']),
      r('deploymentHash', 'execution-root', ['rootDeployment', 'sha256']),
      r('listenAddress', 'webserver', ['host'], addresses.listenHost),
      r('listenPort', 'webserver', ['port'], addresses.listenPort),
      r('internalAddress', 'runtime-root', ['internalAddress'], addresses.internalAddress),
      r('databaseAddress.primary', 'runtime-root', ['database', 'host'], addresses.databaseHost),
      r('databasePort.primary', 'runtime-root', ['database', 'port'], addresses.databasePort),
      r('databaseAddress.secondary', 'access-root', ['database', 'host'], addresses.databaseHost),
      r('databasePort.secondary', 'access-root', ['database', 'port'], addresses.databasePort),
      r('publicOrigin', 'access-root', ['publicOrigin'], addresses.publicOrigin),
      d('storagePlanHash', ['storage', 'plan', 'sha256']),
      d('backendAddress', ['lifecycle', 'lifecycleBaseUrl'], addresses.lifecycleBaseUrl),
    ]
  } catch (_error) { fail() }
}
