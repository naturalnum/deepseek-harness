"""Render the five current-source interface tables deterministically."""
import json


def cell(value):
    """Keep generated table rows on one physical line."""
    if isinstance(value, list):
        value = ', '.join(value)
    return str(value).replace('|', '\\|').replace('\n', ' ')


def table(headers, rows):
    """Render a Markdown table without time-dependent fields."""
    return '| ' + ' | '.join(headers) + ' |\n|' + '|'.join('---' for _ in headers) + '|\n' + ''.join(
        '| ' + ' | '.join(cell(value) for value in row) + ' |\n' for row in rows)


def render(data):
    """Generate the inventory and its machine-readable counterpart."""
    counts = data['counts']
    text = '# Native interface inventory\n\n'
    text += 'Generated by `deploy/upstream/interfaces <upstream-base> --write`; do not edit the tables. The input is the current checkout. TypeScript syntax is parsed without loading plugins. Loader registrations are declarations, not evidence that a deployed account mounted them. Internal reads are structural matches, counted once per source line; public Fiber state checks are excluded.\n\n'
    text += f"Changed Native source files (historical definition, excluding additions): {counts['native_source_files']}; non-seam or unclassified: {counts['non_seam_files']}; internal-read lines outside their plugin's central file: {counts['uncentralized_internal_lines']}.\n\n"
    text += '## Imports\n\n' + table(['Consumer', 'Native module', 'Names', 'Type only'],
        [(f"{r['path']}:{r['line']}", r['module'], r['names'], r['typeOnly']) for r in data['imports']])
    text += '\n## Inheritance\n\n' + table(['Consumer', 'Class', 'Native base', 'Methods', 'Explicit overrides'],
        [(f"{r['path']}:{r['line']}", r['name'], r['module'] + ': ' + r['base'], r['methods'], r['overrides']) for r in data['inheritance']])
    text += '\n## Loader registrations\n\n' + table(['Consumer', 'Entry', 'Native imports referenced', 'Provider expression'],
        [(f"{r['path']}:{r['line']}", r['entry'], r['modules'], r['expression']) for r in data['mounts']])
    text += '\n## Internal reads\n\n' + table(['Consumer', 'Plugin', 'Structure', 'Expression', 'Centralized'],
        [(f"{r['path']}:{r['line']}", r['plugin'], r['categories'], r['code'], r['centralized']) for r in data['internals']])
    added = data['added_native_counts']
    text += (f"\nAdditional Native paths excluded from the historical three counts: {added['total']} "
             f"(source modules {added['src']}; skill resources {added['skill_assets']}; root scripts {added['root_scripts']}). "
             'These paths use the same ledger; a missing row fails the check.\n')
    text += '\n## Native change ledger\n\n' + table(['Path', 'Category', 'Reason', 'Withdrawal condition', 'Disposition', 'Stage status', 'Changed', 'Added'],
        [(r['路径'], r['类别'], r['原因'], r['撤销条件'], r.get('处置', '未登记'), r.get('这一程的状态', '未登记'), r['changed'], r['added']) for r in data['ledger']])
    return {'SEAMS.md': text, 'interfaces.json': json.dumps(data, ensure_ascii=False, indent=2) + '\n'}
