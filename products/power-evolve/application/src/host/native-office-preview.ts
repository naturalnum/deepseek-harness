/** Bounded native Office RPC adaptation over durable Platform preview tasks. */
import { createHash } from 'node:crypto'
import { setTimeout as delay } from 'node:timers/promises'
import { z } from 'zod'
import {
  OFFICE_PREVIEW_ROUTES, OFFICE_PREVIEW_MAX_INPUT_BYTES,
  officePreviewGenerationView, officePreviewPrepareRequest, officePreviewSourcePrepareRequest, officePreviewJobView,
  officePreviewContentView, officePreviewErrorCode,
  type OfficePreviewErrorCode, type OfficePreviewContentView,
  type OfficePreviewGeneration, type OfficePreviewJobId, type OfficePreviewRequestId,
} from '@power-evolve/contracts/office-preview'
import { fileDownloadPath } from '@power-evolve/contracts/file-download'
import { parseArtifactDocumentPath } from '@power-evolve/contracts/artifact-document'
import { PlatformError } from '../contracts.ts'

/** Explicit Host admission, polling and cancellation budgets. */
export interface NativeOfficePreviewOptions {
  readonly pollMs: number
  readonly renderDeadlineMs: number
  readonly cancelTimeoutMs: number
  readonly maxActiveRenders: number
}

/** Authenticated short Platform requests; the transport retains its own request and byte limits. */
export type NativeOfficePreviewCall = (path: string, token: string, input: unknown, signal: AbortSignal) => Promise<unknown>

/** Native multipart fields, excluding the Platform-only PDF digest. */
export type NativeOfficePreviewContent = Omit<OfficePreviewContentView, 'pdfSha256' | 'data'> & { readonly data: Uint8Array }

/** Fixed public preview failure categories, never parser diagnostics. */
export class NativeOfficePreviewError extends Error {
  constructor(readonly code: OfficePreviewErrorCode | 'cancelled') { super('Office preview unavailable') }
}

const rpcIdSchema = z.string().regex(/^[a-f\d]{8}-[a-f\d]{4}-4[a-f\d]{3}-[89ab][a-f\d]{3}-[a-f\d]{12}$/u)
  .pipe(officePreviewPrepareRequest.shape.requestId)
const argsSchema = z.object({ workspaceFileScopeId: officePreviewPrepareRequest.shape.sessionId, path: z.string().min(1).max(1024),
  priority: z.enum(['foreground', 'background']) }).strict()
const sourceSchema = z.object({ absolutePath: z.string(), version: z.string().regex(/^[a-f\d]{64}$/u),
  bytes: z.number().int().nonnegative() }).strict()

function parsed<T>(schema: z.ZodType<T>, raw: unknown): T {
  const result = schema.safeParse(raw)
  if (!result.success) throw new NativeOfficePreviewError('invalid-output')
  return result.data
}

function classified(error: unknown): unknown {
  if (error instanceof PlatformError && error.code === 'office_render_cancelled') {
    return new NativeOfficePreviewError('cancelled')
  }
  if (error instanceof PlatformError && error.code.startsWith('office_render_')) {
    const reason = officePreviewErrorCode.safeParse(error.code.slice('office_render_'.length))
    return new NativeOfficePreviewError(reason.success ? reason.data : 'failed')
  }
  return error
}

/** Own render capacity and cancellation until every short request has settled. */
export class NativeOfficePreview {
  private readonly lifetime = new AbortController()
  private readonly tasks = new Set<Promise<unknown>>()
  private activeRenders = 0

  constructor(private readonly call: NativeOfficePreviewCall, private readonly options: NativeOfficePreviewOptions) {}

  /** Read the authenticated shared converter generation as the native bare string.
   * @param token - current browser credential, never persisted by this adapter.
   * @param rpcId - UUIDv4 generated by the native browser RPC caller.
   * @param args - the native empty argument record.
   * @param signal - browser HTTP response lifetime.
   * @returns the validated converter generation.
   */
  async generation(token: string, rpcId: string, args: unknown, signal: AbortSignal): Promise<OfficePreviewGeneration> {
    rpcIdSchema.parse(rpcId)
    z.object({}).strict().parse(args)
    const upstream = AbortSignal.any([signal, this.lifetime.signal])
    const task = this.readGeneration(token, upstream)
    this.tasks.add(task)
    try { return await task }
    catch (error) {
      if (upstream.aborted) throw new NativeOfficePreviewError('cancelled')
      throw classified(error)
    } finally { this.tasks.delete(task) }
  }

  /** Render one authorized source while keeping native unary HTTP framing.
   * @param token - current browser credential.
   * @param rpcId - stable UUIDv4 used as the owner-scoped Platform request identity.
   * @param args - native Session, virtual source path and scheduling priority.
   * @param signal - browser HTTP response lifetime.
   * @returns complete verified PDF bytes with their original source metadata.
   */
  async render(token: string, rpcId: string, args: unknown, signal: AbortSignal): Promise<NativeOfficePreviewContent> {
    const requestId = rpcIdSchema.parse(rpcId)
    const input = argsSchema.parse(args)
    let path: string
    if (input.path.startsWith('/artifacts/')) {
      parseArtifactDocumentPath(input.path)
      path = input.path
    } else {
      const relative = fileDownloadPath.parse(input.path.startsWith('/workspace/')
        ? input.path.slice('/workspace/'.length) : input.path)
      path = `/workspace/${relative}`
    }
    if (this.activeRenders >= this.options.maxActiveRenders) throw new NativeOfficePreviewError('busy')
    this.activeRenders++
    const task = this.renderFile(token, requestId, { ...input, path }, signal)
    this.tasks.add(task)
    try { return await task } finally { this.activeRenders--; this.tasks.delete(task) }
  }

  /** Cancel owned requests and await bounded cancellation attempts during Host disposal.
   * @returns completion after every admitted request has settled.
   */
  async close(): Promise<void> {
    this.lifetime.abort()
    await Promise.allSettled(this.tasks)
  }

  private async readGeneration(token: string, signal: AbortSignal): Promise<OfficePreviewGeneration> {
    signal.throwIfAborted()
    const raw = await this.call(OFFICE_PREVIEW_ROUTES.generation, token, {}, signal)
    signal.throwIfAborted()
    return parsed(officePreviewGenerationView, raw).generation
  }

  private async renderFile(token: string, requestId: OfficePreviewRequestId, input: z.infer<typeof argsSchema>, signal: AbortSignal): Promise<NativeOfficePreviewContent> {
    const deadline = new AbortController()
    const timer = setTimeout(() => deadline.abort(), this.options.renderDeadlineMs)
    const upstream = AbortSignal.any([signal, this.lifetime.signal, deadline.signal])
    let generation: OfficePreviewGeneration | undefined
    let jobId: OfficePreviewJobId | undefined
    let prepared = false
    let delivered = false
    try {
      generation = await this.readGeneration(token, upstream)
      const sourceRequest = { sessionId: input.workspaceFileScopeId, path: input.path }
      const source = parsed(sourceSchema, await this.call('/native/files/stat', token, sourceRequest, upstream))
      if (source.absolutePath !== sourceRequest.path) throw new NativeOfficePreviewError('source-changed')
      if (source.bytes > OFFICE_PREVIEW_MAX_INPUT_BYTES) throw new NativeOfficePreviewError('input-too-large')
      upstream.throwIfAborted()
      const selection = input.path.startsWith('/artifacts/')
        ? { source: { kind: 'artifact', ...parseArtifactDocumentPath(input.path), sha256: source.version } }
        : { path: fileDownloadPath.parse(input.path.slice('/workspace/'.length)) }
      const request = officePreviewSourcePrepareRequest.parse({ requestId, sessionId: input.workspaceFileScopeId,
        ...selection, priority: input.priority, generation })
      // Admission may commit before its HTTP reply is observed.
      prepared = true
      let job = parsed(officePreviewJobView, await this.call(OFFICE_PREVIEW_ROUTES.prepare, token, request, upstream))
      if (job.generation !== generation) throw new NativeOfficePreviewError('invalid-output')
      jobId = job.jobId
      while (job.state !== 'succeeded') {
        if (job.state === 'failed' || job.state === 'blocked') throw new NativeOfficePreviewError(job.errorCode!)
        if (job.state === 'cancelled') throw new NativeOfficePreviewError('cancelled')
        await delay(this.options.pollMs, undefined, { signal: upstream })
        job = parsed(officePreviewJobView, await this.call(OFFICE_PREVIEW_ROUTES.status, token, { jobId, generation }, upstream))
        if (job.jobId !== jobId || job.generation !== generation) throw new NativeOfficePreviewError('invalid-output')
      }
      const content = parsed(officePreviewContentView,
        await this.call(OFFICE_PREVIEW_ROUTES.content, token, { jobId, generation }, upstream))
      if (content.generation !== generation) throw new NativeOfficePreviewError('invalid-output')
      if (content.absolutePath !== source.absolutePath || content.version !== source.version) {
        throw new NativeOfficePreviewError('source-changed')
      }
      const bytes = Buffer.from(content.data, 'base64')
      if (bytes.length !== content.bytes || createHash('sha256').update(bytes).digest('hex') !== content.pdfSha256) {
        throw new NativeOfficePreviewError('invalid-output')
      }
      upstream.throwIfAborted()
      const { pdfSha256: _digest, data: _encoded, ...native } = content
      delivered = true
      return { ...native, data: new Uint8Array(bytes) }
    } catch (error) {
      if (deadline.signal.aborted) throw new NativeOfficePreviewError('timeout')
      if (signal.aborted || this.lifetime.signal.aborted) throw new NativeOfficePreviewError('cancelled')
      throw classified(error)
    } finally {
      clearTimeout(timer)
      if (prepared && !delivered && generation !== undefined) {
        const cancellation = new AbortController()
        const cancelTimer = setTimeout(() => cancellation.abort(), Math.min(this.options.cancelTimeoutMs, 15_000))
        try {
          const cancelled = parsed(officePreviewJobView, await this.call(OFFICE_PREVIEW_ROUTES.cancel, token,
            jobId === undefined ? { requestId, generation } : { jobId, generation }, cancellation.signal))
          if (cancelled.generation !== generation || (jobId !== undefined && cancelled.jobId !== jobId)) {
            throw new NativeOfficePreviewError('invalid-output')
          }
        } catch (_cancelError) {
          // Cancellation is an intent; an unavailable reply never establishes parser termination.
        } finally { clearTimeout(cancelTimer) }
      }
    }
  }
}
